/**
  * @brief  calibra e encontra um offset de forma dinamica
  * @retval none
  */
void calibrate(void){

	double avg = 0.0;

	for (int i = 0; i < CAL_SAMPLES ; i++)
	{
		avg += get_adc_average();
		HAL_Delay(10); // remover depois
	}
	offset = avg / CAL_SAMPLES;
}

/**
  * @brief  mostra o peso no LCD DISPlAY
  * @retval none
  */
void show_weight(void)
{
	  sprintf(msg, "%0.2f g ", weight);
	  HD44780_Clear();
	  HD44780_SetCursor(2,0);
	  HD44780_PrintStr("Weight Scale");
	  HD44780_SetCursor(10,1);
	  HD44780_SetCursor(4,1);
	  HD44780_PrintStr(msg);
	  HD44780_SetCursor(10,1);
}
/**
  * @brief  calcula o peso
  * @retval none
  */
void get_weight(double adc_mean)
{
	double aux = 0.0;

	aux = adc_mean - offset;

	if( adc_mean < offset)
	{
		weight = 0.0;
	}else{
		weight = (7.62941404 * aux + 4.22272973) - tare_weight;
	}
}

/**
  * @brief  calcula a media das leituras do adc
  * @retval media do adc
  */
double get_adc_average(void)
{
	uint32_t adc = 0;
	double sum = 0.0;
	double average = 0.0;

	for(int i = 0; i < MEAN_SAMPLES; i++)
	{
		adc = read_adc();
		filter = adc*ALFA +(1-ALFA)*filter;
		sum += filter;
	}
	average = sum / (double)MEAN_SAMPLES;

	return average;
}


